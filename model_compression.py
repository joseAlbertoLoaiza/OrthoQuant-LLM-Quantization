def test_model_qa(tokenizer, compressed_model, context, questions):
    """
    Función para realizar predicciones sobre un conjunto de preguntas y un contexto dado.

    Args:
    - tokenizer: Tokenizador del modelo.
    - compressed_model: Modelo comprimido para realizar la inferencia.
    - context: Texto de contexto para las preguntas.
    - questions: Lista de preguntas a responder.

    Prints:
    - La pregunta y la respuesta para cada una de las preguntas.
    """
    for question in questions:
      # Asegurar que haya un token de padding
        if tokenizer.pad_token is None:
            tokenizer.add_special_tokens({'pad_token': tokenizer.eos_token})  # Utilizar el token de fin de secuencia como padding

        # Tokenizar la pregunta y el contexto
        inputs = tokenizer(question, context, return_tensors="pt", padding=True, truncation=True, max_length=512)

        # Record the start time for inference
        start_time = time.time()

        # Realizar la predicción
        outputs = compressed_model(**inputs)

        # Obtener la posición de inicio y fin de la respuesta
        start_index = outputs.start_logits.argmax(dim=1).item()
        end_index = outputs.end_logits.argmax(dim=1).item()

        # Extraer y decodificar la respuesta
        tokens = inputs["input_ids"][0][start_index : end_index + 1]
        answer = tokenizer.decode(tokens, skip_special_tokens=True)

        # Record the end time for inference
        end_time = time.time()

        # Calculate the inference time
        inference_time = end_time - start_time

        # Mostrar la pregunta y la respuesta
        print(f"Question: {question}")
        print(f"Answer: {answer}")
        print(f"Inference time: {inference_time:.4f} seconds\n")

def test_model_generation(tokenizer, compressed_model, queries):
    """
    Function to make predictions on a set of queries using a text generation model.

    Args:
    - tokenizer: Tokenizer for the model.
    - compressed_model: Compressed model for inference.
    - queries: List of queries to answer.

    Prints:
    - The query and the generated response for each of the queries.
    - The inference time for each query.
    """
    # Ensure there is a padding token
    if tokenizer.pad_token is None:
        tokenizer.add_special_tokens({'pad_token': tokenizer.eos_token})  # Use the EOS token as padding

    for query in queries:
        # In this case, the query is just the prompt and context is empty or not used
        inputs = tokenizer(query, return_tensors="pt", padding=True, truncation=True, max_length=512)

        # Mover tensores a la misma GPU donde está el modelo
        inputs = {k: v.to(compressed_model.device) for k, v in inputs.items()}

        # Ensure the attention mask is included
        attention_mask = inputs.get("attention_mask", None)

        # Record the start time for inference
        start_time = time.time()

        # Perform the generative prediction
        outputs = compressed_model.generate(
            inputs["input_ids"],
            attention_mask=attention_mask,  # Pass attention if available
            max_length=25,  # Maximum length of the generated response
            num_return_sequences=1,  # Number of sequences to generate
            no_repeat_ngram_size=2,  # Avoid n-gram repetition
            temperature=0.1,  # Controls the creativity of the responses
            top_k=50,  # Controls the variety of the responses
            #top_p=0.95,  # Controls the cumulative probability
            pad_token_id=tokenizer.pad_token_id,  # Ensure the padding token is used
            eos_token_id=tokenizer.eos_token_id,  # Ensure the EOS token is used
        )

        # Decode the generated response
        generated_text = tokenizer.decode(outputs[0], skip_special_tokens=True)

        # Record the end time for inference
        end_time = time.time()

        # Calculate the inference time
        inference_time = end_time - start_time

        # Print the query, generated response, and inference time
        print(f"Query: {query}")
        print(f"Generated response: {generated_text}")
        print(f"Inference time: {inference_time:.4f} seconds\n")

