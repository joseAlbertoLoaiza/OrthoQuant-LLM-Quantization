class CompressedLinear(nn.Module):
    def __init__(self, compressed_data, method, bias=None):
        super(CompressedLayer, self).__init__()
        self.compressed_data = compressed_data
        self.method = method
        self.bias = bias

        if method not in ['LRA', 'JPEG', 'DCT', 'EDCT']:
            self.out_features, self.in_features = compressed_data['dimensions']

    def __repr__(self):
        # Sobrescribir __repr__ para incluir las dimensiones y si tiene bias
        return f"CompressedLayer(in_features={self.in_features}, out_features={self.out_features}, bias={'True' if self.bias is not None else 'False'})"

    def forward(self, input_tensor):
        """
        Recibe un diccionario que contiene matrices comprimidas y genera una salida similar a una capa lineal.
        La descompresión de las matrices comprimidas se realiza dentro de este método.
        """
        output = None
        device = input_tensor.device


        if self.method not in ['LRA', 'JPEG', 'DCT', 'EDCT']:
            rotation_matrix = model.rotation_matrices.get(self.in_features, None).to(device)
            result = self.decompress_matrix(self.compressed_data, self.method, rotation_matrix.dtype)
            rotation_matrix = rotation_matrix.to(result.dtype)
            result = result.to(device)
            output = torch.matmul(torch.matmul(input_tensor, rotation_matrix.T), result.T)

        else:
            result = self.decompress_matrix(self.compressed_data, self.method)
            result = result.to(device)
            output = torch.matmul(input_tensor, result.T)


        # Realizar la multiplicación de matrices (simulando una capa lineal)
        if self.bias is not None:
            self.bias = self.bias.to(device)
            output = output + self.bias

        return output

    def decompress_matrix(self, compressed_data, method, og_dtype=None, num_segments=5):
        """
        Decompresses a single matrix from its compressed representation.

        Parameters:
            compressed_data (dict): The compressed representation of the matrix.
            method (str): The compression method used ('LRA', 'LocalTopK', 'Decomp', 'Spline', 'JPEG', 'DCT', 'EDCT').
            rotation_matrix (torch.Tensor, optional): The rotation matrix used during compression (if applicable).
            num_segments (int, optional): The number of segments for the 'Decomp' method.

        Returns:
            torch.Tensor: The decompressed matrix.
        """

        # Determine the device (MPS, CUDA, or CPU)
        if torch.backends.mps.is_available():
            device = "mps"
        elif torch.cuda.is_available():
            device = "cuda"
        else:
            device = "cpu"

        if method == 'LRA':
            US_r = compressed_data['US_r']
            Vt_r = compressed_data['Vt_r']

            if device == 'cpu':
                US_r = US_r.to(dtype=torch.float32)
                Vt_r = Vt_r.to(dtype=torch.float32)
            else:
                US_r = US_r.to(device)
                Vt_r = Vt_r.to(device)

            result = torch.matmul(US_r, Vt_r)

        elif method == 'LocalTopK':
            packed_mask = compressed_data['packed_mask']
            non_zero_elements = compressed_data['non_zero_elements']
            dimensions = compressed_data['dimensions']

            S = bitmap_to_matrix(non_zero_elements, packed_mask, dimensions)

            if device == 'cpu':
                S = S.to(dtype=torch.float32)
            else:
                S = S.to(device)

            result = S

        elif method == 'Decomp':
            packed_mask = compressed_data['packed_mask']
            non_zero_elements = compressed_data['non_zero_elements']
            dimensions = compressed_data['dimensions']
            avg_values = compressed_data['avg_values']
            packed_masks = compressed_data['packed_masks']

            D = reconstruct_decomposition(packed_mask, non_zero_elements, dimensions, avg_values, packed_masks)

            if device == 'cpu':
                D = D.to(dtype=torch.float32)
            else:
                D = D.to(device)

            result = D

        elif method == 'Spline':
            spline = compressed_data['spline']
            wt = compressed_data['wt']
            dimensions = compressed_data['dimensions']

            D = reconstruct_spline(spline, wt, dimensions, og_dtype)

            if device == 'cpu':
                D = D.to(dtype=torch.float32)
            else:
                D = D.to(device)

            result = D

        elif method == 'JPEG':
            huffman_encoded = compressed_data['huffman_encoded']
            huff_tree = compressed_data['huff_tree']
            shape = compressed_data['shape']
            Q = compressed_data['Q']

            result = decompress_jpeg(huffman_encoded, huff_tree, shape, Q)

        elif method == 'DCT':
            compressed = compressed_data['compressed']
            shape = compressed_data['shape']
            og_shape = compressed_data['og_shape']

            result = decompress_dct(compressed, shape, og_shape)

        elif method == 'EDCT':
            Ds = compressed_data['Ds']
            shape = compressed_data['shape']

            result = decompress_edct(Ds, shape)

        else:
            raise ValueError(f"Unknown method: {method}")

        return result

