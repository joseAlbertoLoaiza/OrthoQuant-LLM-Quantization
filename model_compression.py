def replace_linear_layers_with_compressed(model, compressed_state_dict, method='Decomp'):
    # Asignar rotation_matrices al modelo como atributo global
    if 'rotation_matrices' in compressed_state_dict:
        model.rotation_matrices = compressed_state_dict['rotation_matrices']


    def traverse_and_replace(module, prefix=""):
        for name, submodule in module.named_children():
            full_name = prefix + name
            # Verificar si el nombre de la capa es una subcadena en alguna de las claves del compressed_state_dict
            for key in compressed_state_dict.keys():
                if full_name in key:
                    # Asegurarse de que el submódulo sea una capa lineal antes de reemplazar
                    if isinstance(submodule, nn.Linear):
                        compressed_data = extract_weight(compressed_state_dict, full_name)
                        bias = extract_bias(compressed_state_dict, full_name)
                        if compressed_data is not None:
                            compressed_layer = CompressedLayer(compressed_data, method, bias)
                            # Reemplazar la capa
                            setattr(module, name, compressed_layer)
                            #print(f"Layer {full_name} reemplazada con CompressedLayer.")
                    break  # Solo reemplazar una vez por cada capa lineal
            # Recursivamente revisar los submódulos
            traverse_and_replace(submodule, prefix=full_name + ".")

    # Iniciar el reemplazo con el modelo principal
    traverse_and_replace(model)
    return

def initialize_cache_and_workers():
    """
    Función para calcular dinámicamente el tamaño de la caché y el número de trabajadores,
    basada en los recursos disponibles del sistema.
    """
    # Obtener recursos del sistema
    total_ram = psutil.virtual_memory().total  # RAM total en bytes
    free_ram = psutil.virtual_memory().available  # RAM libre en bytes
    num_cores = multiprocessing.cpu_count()  # Número total de núcleos de CPU

    # Estimación de la cantidad de memoria que ocupa una matriz descomprimida (en bytes)
    # Este valor depende del tamaño de cada matriz. Asumimos un valor aproximado para cada matriz de 512 KB.
    matrix_size_estimate = 512 * 1024  # Aproximadamente 512 KB por matriz

    # Calcular cuánta memoria queda disponible para las matrices descomprimidas
    memory_for_matrices = free_ram * 0.8  # Asignamos un 80% de la memoria libre para las matrices

    # Calcular el máximo de matrices que podemos almacenar en caché sin exceder la memoria disponible
    max_matrices_in_cache = memory_for_matrices // (7 * matrix_size_estimate)

    # Ajustar para que sea el mayor múltiplo de 7
    max_cache_size = (max_matrices_in_cache // 7) * 7

    # Número de trabajadores (ajustado a la mitad de los núcleos de CPU)
    num_workers = max(2, min(8, num_cores // 2))

    # Caché global con lock
    cache = {}
    cache_lock = threading.Lock()

    # Devuelve los parámetros calculados
    return max_cache_size, num_workers, cache, cache_lock


def decompress_layer(layer):
    """Descomprime una capa y devuelve su resultado"""
    matrix = layer.decompress_matrix(layer.compressed_data).to(layer.bias.device)
    return layer, matrix

def batch_decompress(layers):
    """Descomprime un lote de capas en paralelo sin procesos adicionales"""
    decompressed_matrices = {}

    # Usar hilos en lugar de procesos
    with ThreadPoolExecutor(max_workers=num_workers) as executor:
        results = executor.map(decompress_layer, layers)

    decompressed_matrices.update(dict(results))

    # Agregar a caché con lock
    with cache_lock:
        cache.update(decompressed_matrices)
        while len(cache) > max_cache_size:
            cache.pop(next(iter(cache)), None)  # Eliminar el menos reciente

class DecompLayer(nn.Module):
    def __init__(self, compressed_data, bias=None):
        super().__init__()
        self.compressed_data = compressed_data
        self.out_features, self.in_features = compressed_data['dimensions']
        self.bias = bias if bias is not None else torch.zeros(self.out_features)

    def __repr__(self):
        # Sobrescribir __repr__ para incluir las dimensiones y si tiene bias
        return f"DecompLayer(in_features={self.in_features}, out_features={self.out_features}, bias={'True' if self.bias is not None else 'False'})"


    def forward(self, input_tensor):
        device = input_tensor.device
        rotation_matrix = rotation_matrices.get(self.in_features, None).to(device).to(input_tensor.dtype)

        # Intentar obtener desde caché
        with cache_lock:
            result = cache.get(self, None)

        if result is None:
            result = self.decompress_matrix(self.compressed_data).to(device).to(input_tensor.dtype)
            with cache_lock:
                cache[self] = result

        output = torch.bmm(torch.bmm(input_tensor, rotation_matrix.T.unsqueeze(0)), result.T.unsqueeze(0)) + self.bias
        return output.to(input_tensor.dtype)

    def decompress_matrix(self, compressed_data):
        """Descomprime una matriz desde su representación comprimida."""
        return reconstruct_decomposition(
            compressed_data['non_zero_elements'],
            compressed_data['avg_values'],
            compressed_data['packed_binary_matrix'],
            compressed_data['og_shape_bin']
        )

