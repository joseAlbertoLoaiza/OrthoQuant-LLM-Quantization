def compress_model_matrices(model, weights, method, rotation_matrices=None, num_bits=4):

    if (method not in ['LRA', 'JPEG', 'DCT', 'EDCT']) and (rotation_matrices is None):
        rotation_matrices = compute_rotation_matrices_of_weights(weights)

    compressed_state_dict = {}

    for key, weight in weights.items():
        og_dtype = weight.dtype

        # Verificar si el tensor pertenece a una capa Linear
        is_linear_layer = any(key.startswith(name) and isinstance(layer, torch.nn.Linear)
                              for name, layer in model.named_modules())

        # Solo comprimir si es una matriz 2D, pertenece a una capa Linear y tiene "layer" en el nombre
        if weight.ndimension() == 2 and "layer" in key and is_linear_layer:
            matrix_start_time = time.perf_counter()

            matrix = weight

            num_parameters = matrix.shape[0] * matrix.shape[1] // 2

            if method == 'LRA':
                US_r, Vt_r = low_rank_approximation(matrix, num_parameters)
                compressed_state_dict[key] = {
                    'US_r': US_r.to(dtype=og_dtype),
                    'Vt_r': Vt_r.to(dtype=og_dtype)}
                rotation_matrices = None

            elif method == 'JPEG':
                huffman_encoded, huff_tree, shape, Q = compress_jpeg(matrix)
                compressed_state_dict[key] = {
                    'huffman_encoded': huffman_encoded,
                    'huff_tree': huff_tree,
                    'shape': shape,
                    'Q': Q}
                rotation_matrices = None

            elif method == 'DCT':
                compressed, shape, og_shape = compress_dct(matrix)
                compressed_state_dict[key] = {
                    'compressed': compressed,
                    'shape': shape,
                    'og_shape': og_shape}
                rotation_matrices = None

            elif method == 'EDCT':
                Ds, shape = compress_edct(matrix)
                compressed_state_dict[key] = {
                    'Ds': Ds,
                    'shape': shape}
                rotation_matrices = None

            elif method == 'LocalTopK':
                Q = rotation_matrices[matrix.shape[1]].to(dtype=matrix.dtype)
                D = torch.matmul(matrix, Q.T)
                S = local_topk(D, num_parameters)
                non_zero_elements, packed_mask, dimensions = matrix_to_bitmap(S, og_dtype)

                compressed_state_dict[key] = {
                    'packed_mask': packed_mask,
                    'non_zero_elements': non_zero_elements,
                    'dimensions': dimensions,
                }

            elif method == 'Decomp':
                Q = rotation_matrices[matrix.shape[1]].to(dtype=matrix.dtype)
                D = torch.matmul(matrix, Q.T)
                #S, avg_values, packed_binary_matrix, og_shape_bin = decomposition(D, num_bits)
                #non_zero_elements, packed_mask, dimensions = matrix_to_bitmap(S, og_dtype)
                # compressed_state_dict[key] = {
                #     'packed_mask': packed_mask,
                #     'non_zero_elements': non_zero_elements,
                #     'dimensions': dimensions,
                #     'avg_values': avg_values,
                #     'packed_binary_matrix': packed_binary_matrix,
                #     'og_shape_bin': og_shape_bin
                # }
                dimensions = D.shape
                non_zero_elements, avg_values, packed_binary_matrix, og_shape_bin = decomposition(D, num_bits)
                compressed_state_dict[key] = {
                    'non_zero_elements': non_zero_elements,
                    'dimensions': dimensions,
                    'avg_values': avg_values,
                    'packed_binary_matrix': packed_binary_matrix,
                    'og_shape_bin': og_shape_bin
                }

            elif method == 'Spline':
                Q = rotation_matrices[matrix.shape[1]].to(dtype=matrix.dtype)
                D = torch.matmul(matrix, Q.T)
                spline, wt, dimensions = compute_spline(D)
                compressed_state_dict[key] = {
                    'spline': spline,
                    'wt': wt,
                    'dimensions': dimensions}
        else:
            # Para tensores que no cumplen los requisitos, se almacenan sin cambios
            compressed_state_dict[key] = weight

    # Agregar rotation_matrices al diccionario final
    compressed_state_dict['rotation_matrices'] = rotation_matrices

    return compressed_state_dict

