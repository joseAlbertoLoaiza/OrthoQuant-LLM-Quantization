# Función para calcular el tamaño en bytes de un objeto (tensor, BitVector, numpy array, etc.)
def get_size_in_bytes(obj):
    if isinstance(obj, torch.Tensor):
        return obj.element_size() * obj.numel()
    elif isinstance(obj, np.ndarray):
        return obj.nbytes
    elif isinstance(obj, list) or isinstance(obj, tuple):
        # Si el objeto es una lista, recorrerla y sumar el tamaño de sus elementos
        return sum(get_size_in_bytes(item) for item in obj)
    elif isinstance(obj, dict):
        # Si el objeto es un diccionario, recorrerlo y sumar el tamaño de sus claves y valores
        return sum(get_size_in_bytes(k) + get_size_in_bytes(v) for k, v in obj.items())
    else:
        # En caso de encontrar otro tipo de objeto, devolvemos su tamaño en bytes utilizando sys.getsizeof
        return sys.getsizeof(obj)

# Función para calcular el tamaño de los diccionarios y la reducción de tamaño
def compute_memory_reduction(state_dict, compressed_state_dict):
    # Inicializa el tamaño total para state_dict
    total_size_bytes_state = 0

    #print("\nMemory breakdown for state_dict:")
    for key, tensor in state_dict.items():
        tensor_size = tensor.element_size() * tensor.numel()
        total_size_bytes_state += tensor_size
        #print(f"  {key}: {tensor_size} bytes")

    original_size = total_size_bytes_state
    original_size_gb = original_size / 1e9
    original_size_mb = original_size / 1e6
    print(f"\nTotal memory size of state_dict: {original_size} bytes ({original_size_mb:.2f} MB, {original_size_gb:.6f} GB)")

    # Inicializa el tamaño total para compressed_state_dict
    total_size_bytes_compressed = 0

    #print("\nMemory breakdown for compressed_state_dict:")
    for key, value in compressed_state_dict.items():
        #print(f"Processing {key}...")

        if isinstance(value, dict):
            for subkey, subvalue in value.items():
                subvalue_size = get_size_in_bytes(subvalue)
                total_size_bytes_compressed += subvalue_size
                #print(f"  Subkey: {subkey} - Size: {subvalue_size} bytes")
        else:
            value_size = get_size_in_bytes(value)
            total_size_bytes_compressed += value_size
            #print(f"  Direct value - Size: {value_size} bytes")

    compressed_size = total_size_bytes_compressed
    compressed_size_gb = compressed_size / 1e9
    compressed_size_mb = compressed_size / 1e6
    print(f"\nTotal memory size of compressed_state_dict: {compressed_size} bytes ({compressed_size_mb:.2f} MB, {compressed_size_gb:.6f} GB)")

    # Calcular la reducción de tamaño
    reduction_percentage = 100 * (original_size - compressed_size) / original_size
    print(f"\nReducción en tamaño: {reduction_percentage:.2f}%\n")

