def collect_column_dimensions(weights):
    """
    Extrae las dimensiones de las columnas de todas las matrices de pesos y las almacena en un conjunto.

    Parameters:
        weights (dict): Un diccionario donde las claves son los nombres de las capas y los valores son los tensores de los pesos.

    Returns:
        column_dimensions (set): Un conjunto con las dimensiones de las columnas de las matrices de pesos.
    """
    column_dimensions = set()  # Usamos un set para evitar duplicados

    for key, weight in weights.items():
        if weight.ndimension() == 2:  # Solo matrices 2D
            _, num_columns = weight.shape  # Obtiene el número de columnas
            column_dimensions.add(num_columns)  # Agrega al conjunto

            dtype = weight.dtype

    return column_dimensions, dtype

def compute_rotation_matrices_of_weights(weights):
    """
    Aplica una matriz de rotación Q a cada capa del modelo cuya dimensión de columnas se encuentra en el conjunto.

    Parameters:
        weights (dict): Un diccionario donde las claves son los nombres de las capas y los valores son los tensores de los pesos.

    Returns:
        rotation_matrices (dict): Diccionario de matrices de rotación, donde la clave es la dimensión de las columnas.
    """
    # Paso 1: Extraer las dimensiones de las columnas
    column_dimensions, dtype = collect_column_dimensions(weights)

    # Paso 2: Crear la matriz de rotación para cada dimensión
    rotation_matrices = {}

    for n in column_dimensions:
        #Q = generate_rotation_matrix_Q(n, dtype)
        Q = generate_rotation_matrix_Q(n)
        rotation_matrices[n] = Q  # Almacena la matriz de rotación para cada dimensión

    return rotation_matrices

