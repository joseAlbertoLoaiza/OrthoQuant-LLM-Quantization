def approximate_model_matrices(model, weights, method, rotation_matrices=None, num_bits=4):

    if (method not in ['LRA', 'JPEG', 'DCT', 'EDCT']) and (rotation_matrices is None):
        rotation_matrices = compute_rotation_matrices_of_weights(weights)

    modified_state_dict = {}

    for key, weight in weights.items():
        og_dtype = weight.dtype

        # Verificar si el tensor pertenece a una capa Linear
        is_linear_layer = any(key.startswith(name) and isinstance(layer, torch.nn.Linear)
                              for name, layer in model.named_modules())

        # Solo comprimir si es una matriz 2D, pertenece a una capa Linear y tiene "layer" en el nombre
        if weight.ndimension() == 2 and "layer" in key and is_linear_layer:
            matrix_start_time = time.perf_counter()

            matrix = weight

            num_parameters = int(matrix.shape[0] * matrix.shape[1] * 0.8)

            if method == 'LRA':
                US_r, Vt_r = low_rank_approximation(matrix, num_parameters)
                result = torch.matmul(US_r, Vt_r)
                modified_state_dict[key] = result


            elif method == 'JPEG':
                huffman_encoded, huff_tree, shape, Q = compress_jpeg(matrix)
                result = decompress_jpeg(huffman_encoded, huff_tree, shape, Q)
                modified_state_dict[key] = result

            elif method == 'DCT':
                non_zero_elements, packed_mask, bitmap_shape, shape, og_shape = compress_dct(matrix, og_dtype=matrix.dtype)
                result = decompress_dct(non_zero_elements, packed_mask, bitmap_shape, shape, og_shape)
                result = result.to(matrix.dtype)
                modified_state_dict[key] = result

            elif method == 'EDCT':
                Ds, shape = compress_edct(matrix,og_dtype=matrix.dtype)
                result = decompress_edct(Ds, shape)
                modified_state_dict[key] = result

            elif method == 'LocalTopK':
                Q = rotation_matrices[matrix.shape[1]].to(dtype=matrix.dtype)
                D = torch.matmul(matrix, Q.T)
                S = local_topk(D, num_parameters)


                result = torch.matmul(S, Q)
                modified_state_dict[key] = result

            elif method == 'Decomp':
                Q = rotation_matrices[matrix.shape[1]].to(dtype=matrix.dtype)
                D = torch.matmul(matrix, Q.T)

                dimensions = D.shape
                non_zero_elements, avg_values, packed_binary_matrix, og_shape_bin = decomposition(D, num_bits)
                D_new = reconstruct_decomposition(non_zero_elements, avg_values, packed_binary_matrix, og_shape_bin)

                result = torch.matmul(D_new.to(Q.dtype), Q)
                modified_state_dict[key] = result

            elif method == 'Spline':
                Q = rotation_matrices[matrix.shape[1]].to(dtype=matrix.dtype)
                D = torch.matmul(matrix, Q.T)
                spline, wt, dimensions = compute_spline(D)

                og_dtype = matrix.dtype
                D = reconstruct_spline(spline, wt, dimensions, og_dtype)

                result = torch.matmul(D_new, Q)
                modified_state_dict[key] = result
        else:
            # Para tensores que no cumplen los requisitos, se almacenan sin cambios
            modified_state_dict[key] = weight

    # Agregar rotation_matrices al diccionario final
    modified_state_dict['rotation_matrices'] = rotation_matrices

    return modified_state_dict

def replace_linear_layers_with_approx(model, modified_state_dict):
    # Asignar rotation_matrices al modelo si están presentes
    if 'rotation_matrices' in modified_state_dict:
        model.rotation_matrices = modified_state_dict['rotation_matrices']

    def traverse_and_replace_approx(module, prefix=""):
        for name, submodule in module.named_children():
            full_name = prefix + name

            # Si el submódulo es una capa Linear, intentamos reemplazar sus pesos
            if isinstance(submodule, nn.Linear):
                weight_key = full_name + '.weight'
                bias_key = full_name + '.bias'

                if weight_key in modified_state_dict:
                    # Reemplazar los pesos de la capa
                    approx_weight = modified_state_dict[weight_key]
                    with torch.no_grad():
                        submodule.weight.copy_(approx_weight)

                if submodule.bias is not None and bias_key in modified_state_dict:
                    approx_bias = modified_state_dict[bias_key]
                    with torch.no_grad():
                        submodule.bias.copy_(approx_bias)

            # Recursivamente continuar con los submódulos
            traverse_and_replace_approx(submodule, prefix=full_name + ".")

    # Iniciar el proceso desde el modelo principal
    traverse_and_replace_approx(model)
    return

