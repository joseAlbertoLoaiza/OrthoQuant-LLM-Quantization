def sort_elements_with_indices(D):
    """
    Sorts a tensor and returns the sorted tensor along with the indices
    to reconstruct the original order.

    Args:
        D (torch.Tensor): Tensor to be sorted.

    Returns:
        torch.Tensor: Sorted tensor.
        torch.Tensor: Permutation indices.
    """
    # Flatten the tensor
    flattened_array = D.flatten()

    # Sort the elements and get the indices
    sorted_array, indices = torch.sort(flattened_array)

    return sorted_array, indices

"""### **1.3 Compress bit tensors**"""

def packbits_pytorch(tensor):
    """Simula np.packbits en PyTorch utilizando np.packbits"""
    # Convertir el tensor de PyTorch a un array de Numpy
    tensor_numpy = tensor.numpy()

    # Usamos np.packbits para realizar la conversión
    packed = np.packbits(tensor_numpy, axis=-1)  # Convertir de bits a bytes

    # Regresar el resultado como tensor de PyTorch
    return packed


def unpackbits_pytorch(packed, original_shape):
    """Simula np.unpackbits en PyTorch utilizando np.unpackbits"""

    # Usamos np.unpackbits para convertir los bytes a bits
    unpacked_numpy = np.unpackbits(packed, axis=-1)

    # Regresar el resultado como tensor de PyTorch
    unpacked_tensor = torch.from_numpy(unpacked_numpy).to(dtype=torch.bool)

    # Redimensionar a la forma original deseada
    return unpacked_tensor.view(*original_shape)

"""### **1.4 Matrix to Bitmap**"""

def matrix_to_bitmap(matrix, dtype):
    """
    Converts a sparse matrix (PyTorch tensor) to its bitmap representation.

    Parameters:
        matrix (torch.Tensor): Original matrix, not necessarily binary.

    Returns:
        bit_array (bit vector): Flattened bit array representing the matrix mask.
        non_zero_elements (torch.Tensor): Tensor containing the non-zero elements of the matrix.
        dimensions (tuple): Original dimensions of the matrix.
    """
    # Step 1: Store the matrix dimensions
    original_shape = matrix.shape

    if isinstance(matrix, torch.Tensor):
        # Step 2: Create the binary mask (1 if the element is non-zero, 0 otherwise)
        mask = (matrix != 0).byte()  # Convert to byte tensor
        # Step 3: Extract the non-zero elements
        non_zero_elements = matrix[mask.bool()]
        # Step 4: Pack bits
        packed_mask = packbits_pytorch(mask)

        # Return the objects
        return non_zero_elements.to(dtype=dtype), packed_mask, original_shape

    else:
        # Step 2: Create the binary mask (1 if the element is non-zero, 0 otherwise)
        mask = (matrix != 0).astype(np.uint8)  # Convert to uint8 numpy array
        # Step 3: Extract the non-zero elements
        non_zero_elements = matrix[mask.astype(bool)]
        # Step 4: Pack bits
        packed_mask = np.packbits(mask)

        return non_zero_elements, packed_mask, original_shape

def bitmap_to_matrix(non_zero_elements, packed_mask, original_shape):
    """
    Reconstructs the original matrix from its bitmap representation using bitarray.

    Parameters:
        non_zero_elements (torch.Tensor or np.ndarray): The tensor containing the non-zero elements of the matrix.
        packed_mask (bytes): Packed bitmask representing the matrix.
        original_shape (tuple): The original dimensions of the matrix.

    Returns:
        torch.Tensor or np.ndarray: The reconstructed matrix.
    """
    # Paso 1: Convertir la matriz de bits a tensor booleano o arreglo booleano
    if isinstance(packed_mask, torch.Tensor):
        # Si packed_mask es un tensor de PyTorch, utilizamos unpackbits de PyTorch
        mask = unpackbits_pytorch(packed_mask, original_shape)
    else:
        # Si packed_mask es un arreglo de NumPy, utilizamos unpackbits de NumPy
        mask = np.unpackbits(packed_mask).astype(np.bool_)
        mask = mask[:np.prod(original_shape)].reshape(original_shape)

    # Paso 2: Crear la matriz vacía y restaurar los valores no nulos
    if isinstance(non_zero_elements, torch.Tensor):
        # Si los elementos no nulos son un tensor de PyTorch, usamos torch.zeros
        reconstructed_matrix = torch.zeros(original_shape, dtype=non_zero_elements.dtype, device=non_zero_elements.device)
    else:
        # Si los elementos no nulos son un arreglo de NumPy, usamos np.zeros
        reconstructed_matrix = np.zeros(original_shape, dtype=non_zero_elements.dtype)

    # Paso 3: Rellenar la matriz reconstruida con los elementos no nulos
    reconstructed_matrix[mask] = non_zero_elements

    return reconstructed_matrix
