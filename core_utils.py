"""## **1.- Core Utils**

### **1.1 Generation of common factor matrix**

A rotation matrix **Q** is generated using the following methodology:  

1. Generate a random matrix.  
2. Perform the QR decomposition of this matrix.  
3. Take the **Q** matrix obtained from the QR decomposition.  
4. Ensure that **Q** is a rotation matrix by verifying that:  
   + Its determinant is equal to 1.
"""

def generate_rotation_matrix_Q(n, dtype=torch.bfloat16):
    """
    Generates an n x n rotation matrix Q using TensorFlow and returns it as a PyTorch tensor.

    The columns of Q are orthonormal vectors, and the matrix has a determinant of 1.

    Args:
        n (int): Size of the matrix.
        dtype (torch.dtype): Desired dtype for the output rotation matrix (e.g., torch.float32, torch.float16).

    Returns:
        torch.Tensor: Orthonormal rotation matrix Q as a PyTorch tensor.
    """

    # Generate a random matrix in TensorFlow
    random_matrix = tf.random.normal(shape=(n, n), mean=0.0, stddev=1.0)

    # Apply QR decomposition to obtain an orthonormal matrix Q in TensorFlow
    Q, R = tf.linalg.qr(random_matrix)

    # Ensure that Q is a rotation matrix (det(Q) = 1)
    det_Q = tf.linalg.det(Q)
    if tf.math.less(det_Q, 0):
        # Adjust the sign of the last column to ensure det(Q) = 1
        Q = tf.concat([Q[:, :-1], -Q[:, -1:]], axis=1)  # Multiply the last column by -1

    # Convert Q from TensorFlow to a PyTorch tensor
    Q_torch = torch.tensor(Q.numpy(), dtype=dtype)

    return Q_torch

