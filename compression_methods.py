def compress_edct(A, og_dtype=None, percentage=25):
    if og_dtype is None:
        og_dtype = A.dtype if isinstance(A, torch.Tensor) else torch.float16
    A = A.numpy()
    blocksize = math.gcd(*A.shape)

    h, w = A.shape
    compressed_blocks = []

    for i in range(0, h, blocksize):
        for j in range(0, w, blocksize):
            block = A[i:min(i+blocksize, h), j:min(j+blocksize, w)]
            D = dct2d(block)

            # Calcular el tamaño de la submatriz cuadrada
            num_elements = D.shape[0] * D.shape[1]
            k = int(np.floor(np.sqrt(num_elements * percentage / 100)))

            k = min(k, D.shape[0], D.shape[1])  # Asegurar que no se pase del tamaño del bloque

            Ds = D[:k, :k]  # Extraer la submatriz superior izquierda
            Ds = torch.Tensor(Ds)
            Ds = Ds.to(og_dtype)

            compressed_blocks.append(Ds)  # Guardar también el tamaño original del bloque

    return compressed_blocks, (h, w)  # Retorna la imagen comprimida y su forma

def decompress_edct(compressed_blocks, shape):
    h, w = shape
    blocksize = math.gcd(*shape)
    decompressed = np.zeros((h, w), dtype=np.float32)

    index = 0
    for i in range(0, h, blocksize):
        for j in range(0, w, blocksize):
            block = decompressed[i:min(i+blocksize, h), j:min(j+blocksize, w)]
            block_shape = block.shape

            D_small = compressed_blocks[index]
            D_small = D_small.to(torch.float32).numpy()

            k = D_small.shape[0]

            # Reconstruir la matriz con padding de ceros del tamaño correcto
            D = np.zeros(block_shape, dtype=np.float32)
            D[:k, :k] = D_small

            # Asegurarse de no escribir fuera de los límites
            decompressed[i:i+block_shape[0], j:j+block_shape[1]] = idct2d(D)
            index += 1

    return torch.Tensor(decompressed)

