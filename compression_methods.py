"""### **2.2 Local Top K**

This is one of the methods within the proposed technique. It selects the **k** elements with the largest absolute magnitudes and sets the rest to zero. To ensure that no rows are entirely zero, it selects the **k/n** elements with the largest absolute magnitudes in each of the **n** rows.
"""

def local_topk(D, num_parameters):
    """
    Retiene los num_parameters valores más grandes en magnitud en la matriz D,
    distribuyéndolos equitativamente entre las filas.

    Parámetros:
    D (torch.Tensor): Matriz de entrada.
    num_parameters (int): Número total de valores no ceros deseados en la matriz.

    Retorna:
    torch.Tensor: Matriz modificada con solo los valores top-k por fila.
    """

    S = D.clone()
    num_rows, num_cols = D.shape

    # Calcular cuántos valores mantener por fila
    num_parameters_per_row = max(1, num_parameters // num_rows)

    # Obtener los k valores más grandes en magnitud por fila
    topk_values, _ = torch.topk(D.abs(), num_parameters_per_row, dim=1)

    # Obtener el umbral mínimo por fila para considerar un valor dentro del top-k
    min_topk_values = topk_values[:, -1].view(-1, 1)  # (num_rows, 1)

    # Crear una máscara booleana que indica qué valores mantener en cada fila
    mask = D.abs() >= min_topk_values  # (num_rows, num_cols), cada fila tiene su propia máscara

    # Aplicar la máscara a la matriz original
    S *= mask

    return S

