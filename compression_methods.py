def fractions(array, divisions=20, n_points=100):
    """
    Selects indices uniformly distributed over the first and last fractions of the array
    according to the specified number of divisions, ensuring that the start, middle, and end
    of the array are included.

    Args:
        array (torch.Tensor): 1D tensor with the original values.
        divisions (int): Number of divisions of the array (e.g., 4 for quartiles, 10 for deciles).
        n_points (int): Number of points to select (excluding start, middle, and end).

    Returns:
        list: Selected indices.
    """
    if divisions < 2:
        raise ValueError("The number of divisions must be at least 2.")
    if n_points < 1:
        raise ValueError("The number of points must be at least 1.")

    n = len(array)
    if n < divisions:
        raise ValueError(f"The size of the array must be at least {divisions}.")

    #divisions=10 #For images

    # Calculate the fraction limits
    start_end = n // divisions
    end_start = (divisions - 1) * n // divisions
    first_point = n // 100
    second_quartile = n // 2
    first_quartile = n // 4
    third_quartile = 3 * n // 4
    last_point = (100 - 1) * n // 100

    # Additional points in the fractions
    extra_points = n_points - 5  # Subtract start, quarters, middle, and end
    n_points_start = extra_points // 2
    n_points_end = extra_points - n_points_start

    # Uniformly distributed indices in the first fraction
    start_indices = torch.linspace(0, start_end - 1, n_points_start, dtype=torch.long).tolist() if n_points_start > 0 else []

    # Uniformly distributed indices in the last fraction
    end_indices = torch.linspace(end_start, n - 1, n_points_end, dtype=torch.long).tolist() if n_points_end > 0 else []

    # Ensure including start, middle, quarters, and end
    selected_indices = sorted(set([0, first_point, first_quartile, second_quartile, third_quartile, last_point, n - 1] + start_indices + end_indices))

    return selected_indices

def reconstruct_permutation(wt, n):
    """
    Recupera la secuencia original a partir del Wavelet Tree dividiendo el cálculo en 4 partes para ahorrar memoria.

    Parámetros:
    - wt: Wavelet Tree con el método access(i).
    - n: Número total de elementos en la secuencia original.

    Retorna:
    - Tensor de PyTorch con los índices en su orden original.
    """
    original_indices = torch.empty(n, dtype=torch.int32)  # Reservar memoria

    # Dividir el rango en 4 partes
    chunk_size = n // 4

    for i in range(4):
        start = i * chunk_size
        end = n if i == 3 else (i + 1) * chunk_size  # Última parte toma el resto
        original_indices[start:end] = torch.tensor(
            [wt.access(j) for j in range(start, end)], dtype=torch.int32
        )

    return original_indices

def reconstruct_spline(spline, wt, dimensions, dtype):
    """
    Reconstructs a matrix using a cubic spline approximation and a wavelet tree-based permutation.

    Parameters:
        spline (callable): A precomputed cubic spline function that maps indices to approximated values.
        wt (numpy.ndarray): A wavelet tree stored as a bit array, representing the permutation
                            that maps the sorted sequence back to the original order.
        dimensions (tuple): The original dimensions (rows, cols) of the matrix, used to reshape
                            the reconstructed values.

    Returns:
        torch.Tensor: The reconstructed matrix of shape `dimensions`, where values are estimated
                      using the cubic spline function and reordered using the wavelet tree permutation.
    """

    # Compute the total number of elements in the original matrix
    n = dimensions[0] * dimensions[1]

    # Create an array of indices from 0 to n-1
    x = torch.arange(n)

    # Recover the original order of indices using the wavelet tree
    original_indices = reconstruct_permutation(wt, n)

    # Apply the cubic spline function to obtain approximated values in sorted order
    spline_sorted_values = spline(x)

    # Rearrange the approximated values according to the original indices
    spline_values = spline_sorted_values[torch.argsort(original_indices)]

    # Reshape the values into the original matrix dimensions
    D = spline_values.reshape(dimensions)

    # Convert the NumPy array to a PyTorch tensor
    D = torch.Tensor(D)

    return D.to(dtype=dtype)

