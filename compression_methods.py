"""### **2.6 DCT**"""

def global_topk(D, percentage=50):
    """
    Selecciona los coeficientes con mayor magnitud en valor absoluto, manteniendo un porcentaje específico,
    utilizando la función topk de PyTorch.

    Parámetros:
    - D: Bloque de coeficientes DCT (como un arreglo de numpy o tensor de PyTorch).
    - percentage: Porcentaje de coeficientes a conservar (0-100).

    Retorna:
    - Bloque de coeficientes DCT con el porcentaje especificado de los coeficientes originales.
    """
    # Convertir D a un tensor de PyTorch si no lo es
    D_tensor = torch.tensor(D)

    # Obtener el número total de coeficientes en el bloque DCT
    total_coefficients = D_tensor.numel()
    num_coefficients_to_keep = int((percentage / 100) * total_coefficients)

    # Obtener los coeficientes más grandes en magnitud usando topk
    values, indices = torch.topk(torch.abs(D_tensor).flatten(), num_coefficients_to_keep)

    # Crear un tensor de ceros del mismo tamaño que D
    compressed_D = torch.zeros_like(D_tensor)

    # Colocar los coeficientes seleccionados en el tensor de salida
    compressed_D.flatten()[indices] = D_tensor.flatten()[indices]

    # Convertir de nuevo a numpy si D era numpy
    return compressed_D

# Función que utiliza la DCT de scipy y regresa el resultado como un tensor de PyTorch
def dct_pytorch(input_tensor, type=2, norm='ortho'):
    # Convertir input_tensor a tensor de PyTorch si es un ndarray de NumPy
    if isinstance(input_tensor, np.ndarray):
        input_tensor = torch.tensor(input_tensor, dtype=torch.float32)

    # Asegurarse de que el tensor esté en CPU antes de convertirlo a numpy
    input_tensor_cpu = input_tensor.cpu().numpy()

    # Realizar la DCT usando scipy
    result_dct = dct(dct(input_tensor_cpu.T, norm='ortho').T, norm='ortho')

    # Convertir el resultado nuevamente a tensor de PyTorch y mantener el dtype
    result_tensor = torch.tensor(result_dct, dtype=input_tensor.dtype, device=input_tensor.device)

    return result_tensor

# Función inversa usando IDCT de SciPy y regresando el tensor en PyTorch
def idct_pytorch(input_tensor, type=2, norm='ortho'):

    input_tensor = torch.tensor(input_tensor, dtype=torch.float32)

    # Asegurarse de que el tensor esté en CPU y como un tipo adecuado para SciPy
    input_tensor_cpu = input_tensor.cpu().numpy()

    # Realizar la IDCT usando scipy
    result_idct = idct(idct(input_tensor_cpu.T, norm='ortho').T, norm='ortho')

    # Convertir el resultado nuevamente a tensor de PyTorch y mantener el dtype
    result_tensor = torch.tensor(result_idct, dtype=input_tensor.dtype, device=input_tensor.device)

    return result_tensor

def pad_image_pytorch(A):
    # Asegúrate de que la imagen tenga un tamaño adecuado para la división en bloques
    h, w = A.shape
    pad_h = (8 - (h % 8)) % 8
    pad_w = (8 - (w % 8)) % 8

    A_padded = torch.cat([A, torch.zeros((h, pad_w), dtype=A.dtype)], dim=1)  # Rellenar las columnas
    A_padded = torch.cat([A_padded, torch.zeros((pad_h, A_padded.shape[1]), dtype=A.dtype)], dim=0)  # Rellenar las filas

    return A_padded, (h, w)  # Retorna la imagen con padding y las dimensiones originales

def remove_padding_pytorch(A_padded, og_shape):
    h, w = og_shape
    return A_padded[:h, :w]  # Elimina el padding, devolviendo la forma original

def compress_dct(A, og_dtype=None, percentage=20):
    if og_dtype is None:
        og_dtype = A.dtype if isinstance(A, torch.Tensor) else torch.float16
    start_time = time.time()  # Tiempo de inicio

    # Asegúrate de que A sea un tensor de PyTorch y comprobar el tipo
    A = torch.tensor(A, dtype=torch.float32)
    A, og_shape = pad_image_pytorch(A)  # Agregar relleno a la imagen

    h, w = A.shape
    # Dividir la imagen en bloques de 8x8
    blocks = A.reshape(h // 8, 8, w // 8, 8)  # Dividir en bloques de 8x8

    # Aplicar DCT a cada bloque
    blocks_dct = torch.stack([dct_pytorch(block) for block in blocks.reshape(-1, 8, 8)])

    # Aplicar global_topk a todos los bloques de una vez
    blocks_compressed = torch.stack([global_topk(D, percentage).to(dtype=og_dtype) for D in blocks_dct])

    # Volver a la forma de la matriz original y aplicar matrix_to_bitmap a cada bloque
    compressed = blocks_compressed.reshape(h, w)  # Volver a una sola matriz h, w

    non_zero_elements, packed_mask, bitmap_shape = matrix_to_bitmap(compressed, og_dtype)

    return non_zero_elements, packed_mask, bitmap_shape, (h, w), og_shape  # Retorna la imagen comprimida y su forma


def decompress_dct(non_zero_elements, packed_mask, bitmap_shape, shape, og_shape):
    h, w = shape  # Dimensiones de la imagen

    # Descomprimir la matriz a partir de los elementos no cero y la máscara
    decompressed = bitmap_to_matrix(non_zero_elements, packed_mask, bitmap_shape)

    decompressed = decompressed.reshape(h // 8, 8, w // 8, 8)

    blocks_idct = torch.stack([idct_pytorch(block) for block in decompressed.reshape(-1, 8, 8)])

    # Ahora decompressed debería tener las dimensiones (h, w), que es lo que necesitamos para la imagen final
    decompressed_image = blocks_idct.reshape(h, w)  # Asegurar la forma correcta

    # Eliminar el relleno de la imagen
    decompressed_image = remove_padding_pytorch(decompressed_image, og_shape)

    return decompressed_image

