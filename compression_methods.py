def low_rank_approximation(matrix, num_parameters):
    """
    Computes a low-rank approximation of the given matrix using its SVD decomposition
    and a specified number of parameters (rank `r`).

    Args:
        matrix (torch.Tensor): The input matrix to be approximated.
        num_parameters (int): The desired number of parameters to retain in the approximation.

    Returns:
        torch.Tensor: The truncated left singular vectors multiplied by the truncated singular values (product of U_r and S_r_matrix).
        torch.Tensor: The truncated right singular vectors matrix (Vt_r).
    """
    # Perform Singular Value Decomposition (SVD) on the matrix
    # Perform Singular Value Decomposition (SVD) on the matrix
    orig_dtype = matrix.dtype
    matrix = matrix.to(torch.float32)
    U, S, Vt = torch.linalg.svd(matrix, full_matrices=False)
    U, S, Vt = U.to(orig_dtype), S.to(orig_dtype), Vt.to(orig_dtype)

    # Get the shape of the matrix
    m, n = matrix.shape

    # Calculate the rank `r` using the formula: num_parameters = r * (m + n)
    r = num_parameters // (m + n)  # Rank `r` is computed based on the desired number of parameters

    # Truncate U, S, Vt based on the computed rank `r`
    U_r = U[:, :r]  # Keep the first `r` columns of U (left singular vectors)
    S_r = S[:r]     # Keep the first `r` singular values
    Vt_r = Vt[:r, :]  # Keep the first `r` rows of Vt (right singular vectors)

    # Create a diagonal matrix from the first `r` singular values
    S_r_matrix = torch.zeros(r, r, dtype=U_r.dtype, device=U_r.device)
    S_r_matrix = torch.diag(S_r)  # Fill the diagonal with the singular values

    # Multiply U_r with the diagonal matrix of singular values to get one matrix
    US_r = U_r @ S_r_matrix

    return US_r, Vt_r

