def decompress_jpeg(huffman_encoded, huff_tree, original_shape, Q):
    #start_time = time.time()

    h_padded = (original_shape[0] + 7) // 8 * 8  # Redondeo al múltiplo de 8 más cercano
    w_padded = (original_shape[1] + 7) // 8 * 8

