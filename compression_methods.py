"""## **2.- Compression Methods**

### **2.1 Decomposition**

The main goal of this function is to **preserve the most significant values** in the matrix `D` (the larger values that contain more information) while reducing the storage requirements of the **less significant values** (the smaller ones, which are presumed to contribute less to the data's meaningful structure). To achieve this, the function first identifies and keeps the **larger values** that are outside a specified range \([l, r]\), and then **compresses the smaller values** within the range \([l, r]\) by replacing them with **segment-wise averages**.

This approach is based on the assumption that the values outside this range, where the concavity of the distribution changes, carry the most important information, while the values inside this range are less relevant and can be approximated to save memory.

**How the Decomposition Function Works**
1. **Saving the Larger Values (Preserving Important Data)**:
   - The function begins by identifying the values in `D` that lie outside the range \([l, r]\), where `l` and `r` are the **concavity change points** of the distribution of the values in `D`. These larger values, typically more informative, are preserved in the matrix `S` in their **original form**.
   
2. **Processing the Smaller Values (Memory Optimization)**:
   - The values within the range \([l, r]\), typically smaller and less important, are considered for compression. To reduce memory usage, these values are replaced with their **segment-wise averages**.
   
   - The range \([l, r]\) is divided into `num_segments` sub-ranges, and each sub-range (or segment) contains a subset of the values within the range. The function calculates the **average value** for each segment and substitutes all elements in the segment with the corresponding average. This way, the function reduces the number of distinct values in the range while maintaining the overall structure of the data.
   
**Return Values**:  
   - The function returns three things:  
     - **Matrix `S`**: Contains the values outside the range \([l, r]\), which are the larger, more significant values preserved in their original form.  
     - **Array of Averages**: An array containing the average values for each segment of the smaller values within the range \([l, r]\).  
     - **Array of Flattened Masks**: An array with flattened versions of the masks that indicate the positions of the corresponding averages within the matrix `S`. This mask can be used to locate which elements in `S` will be replaced by their segment-wise averages.  

With these return values, we can construct an approximation of `D` by obtaining a matrix for each average and mask, then adding all these new matrices to `S`, resulting in an approximation of `D`.
"""

def decomposition(D, num_bits):
    """
    Divides the range [l, r] into equal segments for both positive and negative values.
    It calculates the average of the elements within each segment, and then replaces the values
    of the elements in the range [l, r] with the corresponding segment average.
    Values outside this range are kept unchanged.

    :param D: Tensor of values (of type `torch.Tensor`) to be processed.
    :param num_bits: The number of bits for the binary matrix.

    :return:
        - S: Sparse matrix with the elements of highest absolute value
        - avg_values: List with the averages of the elements within each segment.
        - bool_masks: List of boolean masks for each segment.
    """

    dtype=torch.bfloat16

    num_segments = 2**num_bits - 1

    less_segments = num_segments // 2
    more_segments = num_segments - less_segments

    sorted_D, _ = sort_elements_with_indices(D)
    lower_limit, upper_limit = find_concavity_changes(sorted_D)

    l = sorted_D[lower_limit]
    r = sorted_D[upper_limit]

    # Filter the elements outside the range (l, r)
    mask_og = (D <= l) | (D >= r)
    S = D * mask_og.float()  # Keep values outside the range (l, r)
    non_zero_elements = S[mask_og.bool()]

    masks = []  # List to store masks
    avg_values = []  # List to store averages of negative and positive segments

    # --- Process the negative values ---
    mask_neg = (l < D) & (D < 0)  # Filter negative values
    S_neg = D * mask_neg.float()  # Only the negative values

    # --- Process the positive values ---
    mask_pos = (0 < D) & (D < r)  # Filter positive values
    S_pos = D * mask_pos.float()  # Only the positive values

    if mask_neg.sum() > mask_pos.sum():
        num_segments_l = more_segments
        num_segments_r = less_segments
    else:
        num_segments_l = less_segments
        num_segments_r = more_segments

    #print(f'num_segments_l:{num_segments_l}, num_segments_r: {num_segments_r}')

    # Divide the negative range (l, 0) into 'num_segments' segments
    neg_step = (0 - l) / num_segments_l

    for i in range(num_segments_l):
        lower = l + i * neg_step
        upper = l + (i + 1) * neg_step
        mask = (lower < D) & (D <= upper)

        # Extract and average only the elements in the segment
        segment_values = D[mask]
        avg_neg = segment_values.mean() if segment_values.numel() > 0 else torch.tensor(0.0, dtype=dtype)

        # Replace elements in D with the segment average
        S_neg[mask] = avg_neg


    # Divide the positive range (0, r) into 'num_segments' segments
    pos_step = (r - 0) / num_segments_r

    for i in range(num_segments_r):
        lower = 0 + i * pos_step
        upper = 0 + (i + 1) * pos_step
        mask = (lower < D) & (D <= upper)

        # Filter the elements in the segment
        segment_values = D[mask]
        avg_pos = segment_values.mean() if segment_values.numel() > 0 else torch.tensor(0.0, dtype=dtype)

        # Replace elements in D with the segment average
        S_pos[mask] = avg_pos

    S_segments = S_neg + S_pos
    S_segments[mask_og] = 0

    avg_values, packed_binary_matrix, og_shape_bin = compress_matrix_decomp(S_segments)

    # Return S, avg_values, and the boolean masks
    return non_zero_elements, avg_values, packed_binary_matrix, og_shape_bin

def find_concavity_changes(array, slope_threshold=1.0, atol=1e-2):
    """
    Finds the points where the slope is equal to ±45 degrees, indicating concavity changes.

    Parameters:
        array (torch.Tensor): One-dimensional (flattened) tensor.
        slope_threshold (float): Target slope value (default is 1.0 for 45 degrees).
        atol (float): Tolerance to consider a slope as equal to the target.

    Returns:
        list: Indices where the slope is approximately ±slope_threshold.
    """
    if array.dim() != 1:
        raise ValueError("The tensor must be one-dimensional (flattened).")

    downsample_factor = max(1,int(len(array)/(2**11)))

    # Calculate the necessary padding size to make the array divisible
    padding_size = (downsample_factor - len(array) % downsample_factor) % downsample_factor

    # Perform padding with zeros or replicate the last value
    if padding_size > 0:
        padding = torch.zeros(padding_size)  # Padding with zeros
        array_padded = torch.cat((array, padding))
    else:
        array_padded = array

    # Perform downsampling
    downsampled_array = array_padded.view(-1, downsample_factor).mean(dim=1)

    # Calculate dx based on the maximum value of the array
    #dx = 10**(math.floor(math.log10(torch.max(torch.abs(array)).item())) - 2)
