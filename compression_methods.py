def pad_image(A):
    """Añade padding a la imagen para que sus dimensiones sean múltiplos de 8."""
    h, w = A.shape
    pad_h = (8 - (h % 8)) % 8
    pad_w = (8 - (w % 8)) % 8

    A_padded = np.pad(A, ((0, pad_h), (0, pad_w)), mode='constant', constant_values=0)

    return A_padded, (h, w)  # Retorna la imagen con padding y el tamaño original

def compress_jpeg(A, quality=50):
    A = A.detach().float().numpy()
    A, original_shape = pad_image(A)  # Aplicar padding
    #start_time = time.time()
    h, w = A.shape
    compressed = []

    Q = Q50 * (50 / quality)  # Ajuste de cuantización

